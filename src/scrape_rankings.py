"""
Rankings cache loader and optional scraper.

The default rankings live in data/rankings_cache.json (committed to the repo).
If data/custom_rankings_cache.json exists, it takes precedence — generated by
load_custom_rankings_from_excel() when a user uploads their own ranked list.

To manually refresh the default cache from the source page, run this file
directly: python scrape_rankings.py --refresh
"""

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

import requests
from bs4 import BeautifulSoup

from ingest import normalize_name

RANKINGS_URL = "https://www.erikakrousewriter.com/erika-krouses-ocd-ranking-of-483-literary-magazines-for-short-fiction"
CACHE_PATH = Path(__file__).parent.parent / "data" / "rankings_cache.json"
CUSTOM_CACHE_PATH = Path(__file__).parent.parent / "data" / "custom_rankings_cache.json"

# Journals are identified by having "— Score:" in the text
_JOURNAL_RE = re.compile(r"^(.+?)\s+[—–-]\s+Score:\s*([\d.]+)", re.IGNORECASE)
_TIER_RE = re.compile(r"^Tier\s+\d+", re.IGNORECASE)


# ---------------------------------------------------------------------------
# Cache
# ---------------------------------------------------------------------------

def _load_cache() -> list[dict] | None:
    if CACHE_PATH.exists():
        with open(CACHE_PATH, encoding="utf-8") as f:
            return json.load(f)
    return None


def _save_cache(rankings: list[dict]) -> None:
    CACHE_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(CACHE_PATH, "w", encoding="utf-8") as f:
        json.dump(rankings, f, indent=2, ensure_ascii=False)


# ---------------------------------------------------------------------------
# Scraper
# ---------------------------------------------------------------------------

def _fetch_rankings() -> list[dict]:
    resp = requests.get(RANKINGS_URL, timeout=15, headers={"User-Agent": "submissions-advisor/1.0"})
    resp.raise_for_status()
    return _parse_rankings(resp.text)


def _parse_rankings(html: str) -> list[dict]:
    soup = BeautifulSoup(html, "html.parser")
    fetched_at = datetime.now(timezone.utc).isoformat()

    # Find the main content area — skip nav, sidebar, footer
    content = (
        soup.find("article")
        or soup.find("div", class_=re.compile(r"entry-content|post-content|content"))
        or soup.find("main")
        or soup.body
    )

    rankings = []
    rank = 0
    current_tier = None

    for tag in content.find_all(["p", "li", "h2", "h3", "h4"]):
        text = tag.get_text(separator=" ", strip=True)
        # Collapse multiple spaces and normalize dashes
        text = re.sub(r"\s+", " ", text)

        # Track current tier for notes
        if _TIER_RE.match(text):
            current_tier = text.split(",")[0].strip()
            continue

        m = _JOURNAL_RE.match(text)
        if m:
            name = m.group(1).strip().rstrip("—–-").strip()
            score = float(m.group(2))
            rank += 1
            # Grab the first href in this tag as the journal URL
            journal_url = None
            for a in tag.find_all("a", href=True):
                href = a["href"]
                if href.startswith("http") and "erikakrouse" not in href:
                    journal_url = href
                    break
            rankings.append({
                "rank": rank,
                "name": name,
                "normalized_name": normalize_name(name),
                "score": score,
                "tier": current_tier,
                "journal_url": journal_url,
                "notes": text[m.end():].strip().lstrip(",").strip() or None,
                "fetched_at": fetched_at,
            })

    # Deduplicate by normalized_name, keeping first occurrence (correct rank order)
    seen = set()
    deduped = []
    for entry in rankings:
        if entry["normalized_name"] not in seen:
            seen.add(entry["normalized_name"])
            deduped.append(entry)

    for i, entry in enumerate(deduped, start=1):
        entry["rank"] = i

    return deduped


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def _strip_markers(name: str) -> str:
    """Drop the source list's asterisks from a display name.

    Krouse marks online-only magazines "*Joyland" and two print journals
    "Hudson Review (*no simultaneous subs)". The asterisk reads as noise in every
    screen that shows the name; the no-simultaneous note stays as plain text.
    normalize_name already strips punctuation, so normalized_name - the key every
    cache uses - is the same with or without it.
    """
    return re.sub(r"\s+", " ", name.replace("*", "")).strip()


def load_rankings() -> list[dict]:
    """Load rankings — custom cache if present, otherwise default."""
    if CUSTOM_CACHE_PATH.exists():
        with open(CUSTOM_CACHE_PATH, encoding="utf-8") as f:
            return json.load(f)
    cached = _load_cache()
    if cached:
        for r in cached:
            r["name"] = _strip_markers(r["name"])
        return cached
    raise FileNotFoundError(
        f"No rankings cache found at {CACHE_PATH}. "
        "Run scrape_rankings.py --refresh to generate it."
    )


def load_custom_rankings_from_excel(path) -> list[dict]:
    """
    Parse a user-supplied rankings Excel file and write to custom_rankings_cache.json.
    Required columns: rank, name. Optional: score, journal_url, tier.
    """
    import openpyxl

    wb = openpyxl.load_workbook(str(path), data_only=True)
    ws = wb.active

    headers = [
        str(cell.value).strip().lower() if cell.value else ""
        for cell in ws[1]
    ]
    if not {"rank", "name"}.issubset(set(headers)):
        raise ValueError(f"Excel must have 'rank' and 'name' columns. Found: {headers}")

    def _col(row, col_name):
        idx = headers.index(col_name) if col_name in headers else -1
        return row[idx].value if 0 <= idx < len(row) else None

    rankings = []
    for row in ws.iter_rows(min_row=2):
        name = _col(row, "name")
        rank = _col(row, "rank")
        if not name or rank is None:
            continue
        try:
            rank = int(rank)
        except (ValueError, TypeError):
            continue

        score = _col(row, "score")
        journal_url = _col(row, "journal_url")
        tier = _col(row, "tier")
        if tier is None:
            tier = 1 if rank <= 50 else 2 if rank <= 150 else 3 if rank <= 300 else 4

        rankings.append({
            "rank": rank,
            "name": str(name).strip(),
            "normalized_name": normalize_name(str(name).strip()),
            "score": float(score) if score is not None else None,
            "tier": int(tier),
            "journal_url": str(journal_url).strip() if journal_url else "",
            "about_url": "",
            "submit_url": "",
            "fetched_at": None,
        })

    rankings.sort(key=lambda r: r["rank"])
    CUSTOM_CACHE_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(CUSTOM_CACHE_PATH, "w", encoding="utf-8") as f:
        json.dump(rankings, f, indent=2, ensure_ascii=False)
    return rankings


def clear_custom_rankings() -> None:
    """Remove the custom rankings cache, reverting to the default."""
    if CUSTOM_CACHE_PATH.exists():
        CUSTOM_CACHE_PATH.unlink()


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    refresh = "--refresh" in sys.argv
    rankings = load_rankings(refresh=refresh)
    print(f"Loaded {len(rankings)} ranked journals")
    for r in rankings[:10]:
        print(f"  #{r['rank']:3d}  [{r['tier']}]  {r['name']}  (score: {r['score']})")
